    // Signing is optional so F-Droid/CI can produce an unsigned release APK.
    // Local signed builds: copy keystore.properties.example → keystore.properties
    // (or set MUZORA_USE_DEBUG_SIGNING=1 to reuse ~/.android/debug.keystore).
    signingConfigs {
        create("release") {
            val propsFile = rootProject.file("keystore.properties")
            val useDebug = System.getenv("MUZORA_USE_DEBUG_SIGNING")
                ?.equals("1", ignoreCase = true) == true
            val debugKs = file("${System.getProperty("user.home")}/.android/debug.keystore")
            when {
                propsFile.exists() -> {
                    val props = Properties()
                    propsFile.inputStream().use { props.load(it) }
                    storeFile = file(props.getProperty("storeFile"))
                    storePassword = props.getProperty("storePassword")
                    keyAlias = props.getProperty("keyAlias")
                    keyPassword = props.getProperty("keyPassword")
                }
                useDebug && debugKs.exists() -> {
                    storeFile = debugKs
                    storePassword = "android"
                    keyAlias = "androiddebugkey"
                    keyPassword = "android"
                }
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            val releaseSigning = signingConfigs.getByName("release")
            if (releaseSigning.storeFile?.exists() == true) {
                signingConfig = releaseSigning
            }
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
        }
        debug {
            isMinifyEnabled = false
        }
    }

